"""Visible-area metadata for bundled art: fraction of the square layer box covered by the object's alpha bbox
(images are drawn `contain` inside a w×w box). Used by the automated hero-size check (QUALITY_BAR MUST 1).
Run: python3 scripts/assets/meta.py  → src/engine/artMeta.ts"""
import os, json
from PIL import Image
root = os.path.join(os.path.dirname(__file__), '..', '..')
out = {}
box = {}
for folder, prefix in (('obj', 'obj/'), ('3d', '3d/')):
    d = os.path.join(root, 'public', 'art', folder)
    for f in sorted(os.listdir(d)):
        if not f.endswith('.webp'): continue
        im = Image.open(os.path.join(d, f)).convert('RGBA')
        W, H = im.size
        bb = im.getchannel('A').point(lambda a: 255 if a > 24 else 0).getbbox() or (0, 0, W, H)
        S = max(W, H)
        out[prefix + f[:-5]] = round((bb[2] - bb[0]) * (bb[3] - bb[1]) / (S * S), 3)
        # alpha bbox inside the square layer box (image centred, `contain`), as fractions 0..1
        ox, oy = (S - W) / 2, (S - H) / 2
        box[prefix + f[:-5]] = [round((bb[0] + ox) / S, 3), round((bb[1] + oy) / S, 3), round((bb[2] + ox) / S, 3), round((bb[3] + oy) / S, 3)]
with open(os.path.join(root, 'src', 'engine', 'artMeta.ts'), 'w') as fh:
    fh.write('/** Generated by scripts/assets/meta.py — visible fraction of the square layer box per bundled image. */\n')
    fh.write('export const ART_FILL: Record<string, number> = ' + json.dumps(out, separators=(',', ':')) + ';\n')
    fh.write('/** visible bbox [x0, y0, x1, y1] inside the square layer box (fractions) */\n')
    fh.write('export const ART_BOX: Record<string, [number, number, number, number]> = ' + json.dumps(box, separators=(',', ':')) + ';\n')
print(len(out), 'entries')
